/// 説明書の見出し1つ分と、その中の最後に出す参考資料の図(説明書だけ)
class SetsumeishoKoumoku {
  const SetsumeishoKoumoku(
    this.setsu, {
    this.zuSetsumei = '',
    this.zu = const [],
  });
  final ShiyouSetsu setsu;

  /// 図の説明(図の上に出す)
  final String zuSetsumei;

  /// 図の画像のパス
  final List<String> zu;
}

/// 説明書のグループ(区切りの名前と、その中の見出し)
