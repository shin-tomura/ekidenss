// 隠れた逸材(1.8.8)
// 13分台でない新入生(入学時5000mが14分台・15分台)のうち、itsuzaiWariai%を、本当は13分台の力が
// ある選手にする(公立高校で記録会にあまり出ていなかったなどで、持ちタイムが実力より遅い選手)。
// ・入学時の基本走力と基本走力の上限を、13分台の新入生と同じ決め方で決め直す
//   (入学時に13分台の力があるので、成長タイプによらず、5月のインカレの1万とハーフで速さが分かる。
//   5000mは、上限に届いたあとの選手どうしの差が小さく、スパート力の差のほうが大きいので目立たない)
// ・入学時5000mの記録(持ちタイム)・素質・能力値(スパート力・ペース変動対応力など)・成長タイプは、
//   ふつうの新入生と同じ決め方のまま(スカウトの画面などで、持ちタイムと能力値から見分けられないように。
//   高校でレースに出ていないのでスパートやペースの上げ下げは苦手、という形になる)
// ・逸材かどうかは保存しない(箱庭モードの上限の表示では分かる)。新入生を作ったときにログに人数を出す
// ・サプライズなので、説明書・生成AI向けの仕様・変更履歴には書かない(変更履歴は「新入生の構成を一部見直した」)
// ・割合は、限界突破の運で化ける選手がトップ10に入る確率を参考に、シミュレーションで決めた
//   (逸材の道で増える分が、運で化ける分の半分くらいになるように。持ちタイムによらず同じ割合)。
//   全大学で年9人くらい。名声が最下位の大学にも3年に1回くらい入り、そのうち5月のハーフで
//   いきなり1年生の30位以内に入るのは8年に1回くらい。逸材が4年で学年10位以内に入るのは14%くらい
//   (13分台の新入生は約20%)。学年10位以内に入る14分30秒台以下の選手は年1.6人から2.1人になる。
//   10年に1人級の最速は、ハーフで2秒速くなる程度(順位と秒数は、基本走力だけで比べた値)
// ------------------------------------------------------------

/// 隠れた逸材にする新入生の割合(%)。13分台でない新入生のうち(1.8.8)
const int itsuzaiWariai = 7;

/// 新入生を隠れた逸材にする(1.8.8)
/// SenshuShokitiで、入学時5000mの記録と上限を決めたあと、理論タイムを計算する前に呼ぶ。
/// 入学時の基本走力と上限を、13分台の新入生(素質1550〜1600)と同じ決め方で決め直す。
/// 入学時5000mの記録・素質・能力値は変えない
void itsuzaiNiSuru(SenshuData senshu, Random random) {
  // 本当の力(13分台の新入生の素質と、その入学時5000mの記録)
  final int sosituHontou = random.nextInt(51) + 1550; // 1550から1600まで
  final double kirokuHontou = nyuugakuji5000Juusanpundai(sosituHontou, random);
  // 入学時の基本走力(SenshuShokitiの13分台の新入生と同じ式。b=1645のときの値)
  final int aMinInt =
      (1550.0 * 1550.0 * 0.0333 - 1550.0 * 114.25 + TEISUU.MAGICNUMBER)
          .toInt();
  final double tani = 1000.0 / (1680.0 - 1550.0);
  final int aInt = aMinInt + ((sosituHontou - 1550) * tani).toInt();
  senshu.a = aInt * 0.000000001;
  senshu.b = 1645.0 * 0.0001;
  // 上限は、本当の入学時5000mの記録で決める
  senshu.magicnumber = joukaiMagicnumberFromNyuugakuji5000(kirokuHontou);
}

